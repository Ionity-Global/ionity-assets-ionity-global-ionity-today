// Generates firmware/include/nobify_config.h from firmware/nobify.config.yaml
// so the ESP32-S3 firmware carries no YAML parser. Run: npm run gen:firmware
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { parse as parseYaml } from 'yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fwDir = resolve(__dirname, '..', '..', 'firmware');
const yamlPath = resolve(fwDir, 'nobify.config.yaml');
const outPath = resolve(fwDir, 'include', 'nobify_config.h');

if (!existsSync(yamlPath)) {
  console.error(`Missing ${yamlPath}`);
  process.exit(1);
}

const c = parseYaml(readFileSync(yamlPath, 'utf8')) || {};
const g = (o, ...keys) => keys.reduce((v, k) => (v == null ? v : v[k]), o);
const s = (v, d = '') => JSON.stringify(v ?? d);          // quoted C string
const n = (v, d = 0) => (v == null ? d : Number(v));
const fl = (v, d = 0) => { const x = Number(v == null ? d : v); return (Number.isInteger(x) ? x.toFixed(1) : String(x)) + 'f'; };
const b = (v, d = false) => (v == null ? d : (v === true || v === 'true') ? 1 : 0);
const hexColor = (v, d) => {
  const m = String(v ?? d).replace('#', '');
  return `0x${(m.length === 6 ? m : d.replace('#', '')).toUpperCase()}`;
};

const out = `// AUTO-GENERATED by server/scripts/gen-firmware-config.mjs
// Source: firmware/nobify.config.yaml  —  DO NOT EDIT BY HAND.
#pragma once

// ---- Device ----
#define NB_DEVICE_ID           ${s(g(c, 'device', 'id'), 'esp32-s3-01')}
#define NB_DEVICE_NAME         ${s(g(c, 'device', 'name'), 'Nobify Sensor')}

// ---- Firmware + OTA ----
#define NB_FW_VERSION          ${s(g(c, 'firmware', 'version'), '1.0.0')}
#define NB_OTA_ENABLED         ${b(g(c, 'ota', 'enabled'), true)}
#define NB_OTA_CHECK_MS        ${n(g(c, 'ota', 'check_interval_ms'), 900000)}
#define NB_OTA_ARDUINO         ${b(g(c, 'ota', 'arduino_ota'), true)}
#define NB_OTA_ARDUINO_PASS    ${s(g(c, 'ota', 'arduino_ota_password'), '')}

// ---- WiFi ----
#define NB_WIFI_SSID           ${s(g(c, 'wifi', 'ssid'))}
#define NB_WIFI_PASSWORD       ${s(g(c, 'wifi', 'password'))}
#define NB_WIFI_HOSTNAME       ${s(g(c, 'wifi', 'hostname'), 'nobify-esp32s3')}

// ---- Server ----
#define NB_SERVER_URL          ${s(g(c, 'server', 'url'))}
#define NB_INGEST_PATH         ${s(g(c, 'server', 'ingest_path'), '/api/ingest')}
#define NB_INGEST_KEY          ${s(g(c, 'server', 'ingest_key'))}
#define NB_POST_INTERVAL_MS    ${n(g(c, 'server', 'post_interval_ms'), 1000)}
#define NB_HEARTBEAT_MS        ${n(g(c, 'server', 'heartbeat_ms'), 15000)}

// ---- mmWave 24GHz radar ----
#define NB_MMWAVE_UART_RX      ${n(g(c, 'mmwave', 'uart_rx'), 18)}
#define NB_MMWAVE_UART_TX      ${n(g(c, 'mmwave', 'uart_tx'), 17)}
#define NB_MMWAVE_BAUD         ${n(g(c, 'mmwave', 'baud'), 256000)}
#define NB_MMWAVE_MAX_CM       ${n(g(c, 'mmwave', 'max_distance_cm'), 600)}
#define NB_MMWAVE_MIN_CM       ${n(g(c, 'mmwave', 'min_distance_cm'), 20)}
#define NB_CLUTTER_SUPPRESS    ${b(g(c, 'mmwave', 'clutter_suppression'), true)}
#define NB_BG_CALIB_MS         ${n(g(c, 'mmwave', 'background_calibration_ms'), 6000)}
#define NB_MICRO_MOTION_THRESH ${n(g(c, 'mmwave', 'micro_motion_threshold'), 8)}
#define NB_MOVEMENT_ENABLED    ${b(g(c, 'mmwave', 'movement', 'enabled'), true)}
#define NB_APPROACH_SPEED_CMS  ${n(g(c, 'mmwave', 'movement', 'approach_speed_cms'), 2)}
#define NB_LIGHT_ENABLED       ${b(g(c, 'mmwave', 'ambient_light', 'enabled'), true)}
#define NB_DARK_LUX            ${n(g(c, 'mmwave', 'ambient_light', 'dark_lux_threshold'), 5)}
#define NB_LUX_ADC_GPIO        ${n(g(c, 'mmwave', 'ambient_light', 'adc_gpio'), 1)}

// ---- WiFi CSI presence ----
#define NB_CSI_ENABLED         ${b(g(c, 'wifi_csi', 'enabled'), true)}
#define NB_CSI_VAR_THRESH      ${fl(g(c, 'wifi_csi', 'variance_threshold'), 12)}
#define NB_CSI_WINDOW          ${n(g(c, 'wifi_csi', 'window'), 32)}

// ---- LEDs ----  BLUE = WiFi CSI, ORANGE = mmWave
#define NB_LED_WIFI_GPIO       ${n(g(c, 'leds', 'wifi', 'gpio'), 47)}
#define NB_LED_MMWAVE_GPIO     ${n(g(c, 'leds', 'mmwave', 'gpio'), 48)}
#define NB_LED_WIFI_COLOR      ${hexColor(g(c, 'leds', 'wifi', 'color'), '#1e90ff')}
#define NB_LED_MMWAVE_COLOR    ${hexColor(g(c, 'leds', 'mmwave', 'color'), '#ff8c00')}
#define NB_LED_BRIGHTNESS      ${n(g(c, 'leds', 'brightness'), 160)}
#define NB_LED_NEOPIXEL        ${b(g(c, 'leds', 'neopixel'), true)}

// ---- Display ----
#define NB_DISPLAY_ENABLED     ${b(g(c, 'display', 'enabled'), true)}
#define NB_DISPLAY_WIDTH       ${n(g(c, 'display', 'width'), 240)}
#define NB_DISPLAY_HEIGHT      ${n(g(c, 'display', 'height'), 320)}
#define NB_DISPLAY_ROTATION    ${n(g(c, 'display', 'rotation'), 1)}
`;

writeFileSync(outPath, out);
console.log(`Generated ${outPath} from ${yamlPath}`);
